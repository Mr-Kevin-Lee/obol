//! Hand-rolled SimpleFIN v2 client (issue 37). Covers only what obol
//! needs: claiming a Setup Token into an Access URL, and reading account
//! balances. SimpleFIN types stay inside this module and
//! `simplefin_provider.rs`; everything else sees the `Provider` trait.
//!
//! The Access URL carries Basic Auth credentials, so it is only ever held
//! in a `Secret`, sent to HTTPS (or loopback, for tests), and never put in
//! an error message.

use std::time::Duration;

use base64::engine::general_purpose::STANDARD;
use base64::Engine;
use reqwest::Url;
use secrecy::{ExposeSecret, Secret};
use serde::Deserialize;
use thiserror::Error;

#[derive(Debug, Error)]
pub enum SimpleFinError {
    #[error("network/transport error: {0}")]
    Transport(reqwest::Error),
    #[error("setup token is not valid base64 containing a URL")]
    InvalidSetupToken,
    #[error("the Access URL returned by SimpleFIN is not a valid URL")]
    InvalidAccessUrl,
    #[error("SimpleFIN URLs must use https")]
    InsecureUrl,
    /// HTTP 403 on claim: the token doesn't exist or was already claimed,
    /// which may mean someone else claimed it first.
    #[error("claim rejected (HTTP 403): the setup token is invalid or already claimed")]
    ClaimRejected,
    #[error("access denied (HTTP {0}): the Access URL is invalid or was revoked")]
    AccessDenied(u16),
    #[error("unexpected SimpleFIN response (HTTP {status})")]
    UnexpectedStatus { status: u16 },
    #[error("failed to parse SimpleFIN response: {0}")]
    Parse(#[from] serde_json::Error),
}

/// An entry of `AccountSet.errlist`. Codes are `gen.*`, `con.*` or
/// `act.*`; unknown subcodes should be read as the bare prefix.
#[derive(Debug, Clone, Deserialize)]
pub struct SimpleFinApiError {
    pub code: String,
    #[serde(default)]
    pub msg: String,
    #[serde(default)]
    pub conn_id: Option<String>,
    #[serde(default)]
    pub account_id: Option<String>,
}

#[derive(Debug, Clone, Deserialize)]
pub struct SimpleFinConnection {
    pub conn_id: String,
    pub name: String,
}

#[derive(Debug, Clone, Deserialize)]
pub struct SimpleFinAccount {
    pub id: String,
    pub name: String,
    pub conn_id: String,
    /// A numeric string, per the protocol.
    pub balance: String,
    /// Empty for a balances-only request.
    #[serde(default)]
    pub transactions: Vec<SimpleFinTransaction>,
}

#[derive(Debug, Clone, PartialEq, Deserialize)]
pub struct SimpleFinTransaction {
    /// Unique within its account, never across accounts.
    pub id: String,
    /// Unix seconds; may be 0 while pending.
    pub posted: i64,
    /// A numeric string; positive is money in.
    pub amount: String,
    pub description: String,
    #[serde(default)]
    pub pending: bool,
}

/// The transactions a `get_accounts` request asks for: those posted on or
/// after `start` and before `end` (Unix seconds), for `accounts`, or for
/// every account when that's empty. The Bridge serves at most 90 days per
/// request.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct TransactionWindow {
    pub start: i64,
    pub end: Option<i64>,
    pub accounts: Vec<String>,
}

#[derive(Debug, Clone, Deserialize)]
pub struct AccountSet {
    #[serde(default)]
    pub errlist: Vec<SimpleFinApiError>,
    #[serde(default)]
    pub connections: Vec<SimpleFinConnection>,
    #[serde(default)]
    pub accounts: Vec<SimpleFinAccount>,
}

pub struct SimpleFinClient {
    http: reqwest::Client,
}

impl Default for SimpleFinClient {
    fn default() -> Self {
        Self {
            // No redirects: `require_secure` only vets the first URL, so a
            // 3xx must not carry the credentials to a plain-http host.
            http: reqwest::Client::builder()
                .redirect(reqwest::redirect::Policy::none())
                .timeout(Duration::from_secs(30))
                .build()
                .expect("reqwest client with a timeout always builds"),
        }
    }
}

impl SimpleFinClient {
    /// Exchanges a Setup Token (generated by the user at the Bridge) for an
    /// Access URL. One-time: a second claim of the same token is a 403.
    pub async fn claim(&self, setup_token: &str) -> Result<Secret<String>, SimpleFinError> {
        let decoded = STANDARD
            .decode(setup_token.trim())
            .map_err(|_| SimpleFinError::InvalidSetupToken)?;
        let claim_url = std::str::from_utf8(&decoded)
            .ok()
            .and_then(|s| Url::parse(s).ok())
            .ok_or(SimpleFinError::InvalidSetupToken)?;
        require_secure(&claim_url)?;

        let response = self
            .http
            .post(claim_url)
            .send()
            .await
            .map_err(transport_error)?;
        match response.status().as_u16() {
            200 => {}
            403 => return Err(SimpleFinError::ClaimRejected),
            status => return Err(SimpleFinError::UnexpectedStatus { status }),
        }

        let body = response.text().await.map_err(transport_error)?;
        let access_url = body.trim();
        let parsed = Url::parse(access_url).map_err(|_| SimpleFinError::InvalidAccessUrl)?;
        require_secure(&parsed)?;
        Ok(Secret::new(access_url.to_string()))
    }

    /// `GET <access url>/accounts?version=2&balances-only=1`. reqwest turns
    /// the credentials embedded in the URL into a Basic Auth header.
    pub async fn get_balances(
        &self,
        access_url: &Secret<String>,
    ) -> Result<AccountSet, SimpleFinError> {
        self.fetch_accounts(access_url, &[("balances-only", "1".to_string())])
            .await
    }

    /// `GET <access url>/accounts?version=2&start-date=…`: balances plus
    /// the posted transactions in `window`. Pending ones aren't requested.
    pub async fn get_accounts(
        &self,
        access_url: &Secret<String>,
        window: &TransactionWindow,
    ) -> Result<AccountSet, SimpleFinError> {
        let mut query = vec![("start-date", window.start.to_string())];
        query.extend(window.end.map(|end| ("end-date", end.to_string())));
        query.extend(window.accounts.iter().map(|id| ("account", id.clone())));
        self.fetch_accounts(access_url, &query).await
    }

    async fn fetch_accounts(
        &self,
        access_url: &Secret<String>,
        query: &[(&str, String)],
    ) -> Result<AccountSet, SimpleFinError> {
        let mut url =
            Url::parse(access_url.expose_secret()).map_err(|_| SimpleFinError::InvalidAccessUrl)?;
        require_secure(&url)?;
        url.path_segments_mut()
            .map_err(|_| SimpleFinError::InvalidAccessUrl)?
            .pop_if_empty()
            .push("accounts");
        url.query_pairs_mut()
            .append_pair("version", "2")
            .extend_pairs(query);

        let response = self.http.get(url).send().await.map_err(transport_error)?;
        match response.status().as_u16() {
            200 => {}
            status @ (401 | 403) => return Err(SimpleFinError::AccessDenied(status)),
            status => return Err(SimpleFinError::UnexpectedStatus { status }),
        }

        let body = response.text().await.map_err(transport_error)?;
        Ok(serde_json::from_str(&body)?)
    }
}

/// `without_url` because reqwest errors embed the request URL, which here
/// carries the Access URL's credentials.
fn transport_error(err: reqwest::Error) -> SimpleFinError {
    SimpleFinError::Transport(err.without_url())
}

/// HTTPS only, except loopback so tests can use a local mock server.
fn require_secure(url: &Url) -> Result<(), SimpleFinError> {
    let loopback = matches!(url.host_str(), Some("127.0.0.1" | "localhost"));
    match url.scheme() {
        "https" => Ok(()),
        "http" if loopback => Ok(()),
        _ => Err(SimpleFinError::InsecureUrl),
    }
}

#[cfg(test)]
