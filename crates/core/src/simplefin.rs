    /// `http://user:pass@127.0.0.1:<port><path>` for the mock server.
    fn access_url_for(server: &MockServer, url_path: &str) -> Secret<String> {
        let base = server.uri().replace("http://", "http://user:pass@");
        Secret::new(format!("{base}{url_path}"))
    }

    fn setup_token_for(server: &MockServer) -> String {
        STANDARD.encode(format!("{}/simplefin/claim/abc123", server.uri()))
    }

    fn accounts_body() -> serde_json::Value {
        json!({
            "errlist": [],
            "connections": [
                { "conn_id": "c1", "name": "Chase", "org_id": "o1", "sfin_url": "https://x" }
            ],
            "accounts": [
                {
                    "id": "acc_1", "name": "Checking", "conn_id": "c1", "currency": "USD",
                    "balance": "100.23", "available-balance": "75.23",
                    "balance-date": 978366153, "transactions": []
                }
            ]
        })
    }

    #[tokio::test]
    async fn claim_returns_the_access_url() {
        let server = MockServer::start().await;
        Mock::given(method("POST"))
            .and(path("/simplefin/claim/abc123"))
            .respond_with(ResponseTemplate::new(200).set_body_string("http://u:p@127.0.0.1/x\n"))
            .mount(&server)
            .await;

        let url = SimpleFinClient::default()
            .claim(&setup_token_for(&server))
            .await
            .unwrap();
        assert_eq!(url.expose_secret(), "http://u:p@127.0.0.1/x");
    }

