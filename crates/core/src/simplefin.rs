    #[tokio::test]
    async fn get_balances_body_that_is_not_json_is_a_parse_error() {
        let server = MockServer::start().await;
        Mock::given(method("GET"))
            .respond_with(ResponseTemplate::new(200).set_body_string("<html>"))
            .mount(&server)
            .await;

        let err = SimpleFinClient::default()
            .get_balances(&access_url_for(&server, "/simplefin"))
            .await
            .unwrap_err();
        assert!(matches!(err, SimpleFinError::Parse(_)));
    }
